export function formatDate(lang: Lang, d: Date | string, opts: Intl.DateTimeFormatOptions = { month: "short", day: "numeric", year: "numeric" }) {
  const date = typeof d === "string" ? new Date(d) : d;
  return date.toLocaleDateString(lang === "es" ? "es-US" : "en-US", opts);
}
